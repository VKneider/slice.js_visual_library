/**
 * `routes.js` is what the Router knows. Every real documentation page is listed
 * explicitly and pointed at the App shell, so a `/docs/...` path that is not a
 * page matches nothing at all — and the Router's own fallback (matchRoute →
 * the `/404` route) renders NotFound instead of wrapping an empty page in the
 * docs layout.
 *
 * Each entry also carries `metadata.title`. The Router applies it on every
 * navigation (including the first), which replaces the hand-written title map
 * the App shell used to keep. The titles come from the same manifest the server
 * prerenders, so the client and the server cannot disagree.
 *
 * @param {Array<{route?: string}>} [entries] docs index entries
 * @param {{ titles?: Record<string, string> }} [options]
 */
const generateMainRoutesFile = (entries = [], options = {}) => {
  const titles = options.titles || {};

  const docRoutes = entries
    .map((entry) => entry?.route)
    .filter((route) => typeof route === 'string' && route.startsWith('/docs/'))
    .map((route) => (route.length > 1 ? route.replace(/\/+$/, '') : route))
    .sort();

  // `/docs` (the hub) plus one line per generated page. No `/docs/${...}`
  // patterns: they would claim any `/docs/<a>/<b>` (or `<a>`) and wrap a URL that
  // does not exist in the docs layout. With an explicit table, such a path
  // matches nothing and the Router falls back to /404 → NotFound.
  const docsShellRoutes = ['/docs', ...docRoutes];

  /** One route line; `comma` is false for the last entry. */
  const routeLine = (route, component, comma = true) => {
    const path = String(route).replace(/'/g, "\\'");
    const title = titles[route];
    const metadata = title ? `, metadata: { title: ${JSON.stringify(title)} }` : '';
    return `  { path: '${path}', component: '${component}'${metadata} }${comma ? ',' : ''}`;
  };

  const lines = [];
  lines.push('// Auto-generated by parser/index.js. Do not edit manually.');
  lines.push('const routes = [');
  lines.push(routeLine('/', 'App'));
  // Persistent component-testing harness route. Kept here (not derived from
  // markdown) so it survives every `docs:generate` regeneration of routes.js.
  lines.push(routeLine('/__test', 'TestHarness'));
  // Hidden internal sandbox for hand-testing services (e.g. DragDropService).
  // Not in the navbar; kept here so it also survives `docs:generate`.
  lines.push(routeLine('/playground', 'Playground'));
  // Game route - standalone 3D aim trainer.
  lines.push(routeLine('/game', 'GamePage'));
  // Theme Creator - standalone theme-token editor. Top-level like /playground and
  // /game, so it renders outside the AppShell and builds its own navbar.
  lines.push(routeLine('/theme-creator', 'ThemeCreator'));
  docsShellRoutes.forEach((route) => {
    lines.push(routeLine(route, 'App'));
  });
  lines.push(routeLine('/404', 'NotFound', false));
  lines.push('];');
  lines.push('');
  lines.push('export default routes;');
  lines.push('');

  return lines.join('\n');
};

export { generateMainRoutesFile };
